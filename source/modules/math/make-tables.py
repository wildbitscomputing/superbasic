"""Emit 65 quarter-wave anchors as byte-plane Q2.30 tables.

Sines: 260 bytes shared by sin/cos (cos uses index 64-i).
Angles: 260 bytes avoid a multiply to reconstruct the anchor angle.
Sixths: 260 bytes avoid dividing the cubic coefficient by six at runtime.
The generated constants need no runtime floating-point initialisation.
"""

import math

SCALE = 1 << 30
ANGLES = [round(i * math.pi / 128 * SCALE) for i in range(65)]
SINES = [round(math.sin(i * math.pi / 128) * SCALE) for i in range(65)]
SIXTHS = [round(math.sin(i * math.pi / 128) / 6 * SCALE) for i in range(65)]


def main():
    print("; Generated by math/make-tables.py. Do not edit.")
    print("\t\t.section code")
    for name, values in [("Angles", ANGLES), ("Sines", SINES), ("Sixth", SIXTHS)]:
        for byte in range(4):
            print(f"Trig{name}{byte}:")
            for start in range(0, 65, 16):
                chunk = values[start:start + 16]
                print("\t\t.byte " + ",".join(f"${(n >> (byte*8)) & 255:02x}" for n in chunk))
    print("\t\t.send code")


if __name__ == "__main__":
    main()
